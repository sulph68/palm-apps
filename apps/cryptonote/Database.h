/* Prefs > Show Hidden - kept OUT of ApplicationPreferenceType on purpose: that
 * struct is the "saved" (HotSync-backed) prefs blob, and this setting is meant
 * to behave like a local, unsynced default (mirrors Address35's A35Defaults).
 * Stored under dbUnsavedPrefID with PrefSetAppPreferences(..., saved=false). */
/* field is "defVer", not "version" -- this file #defines version 0x03003000
 * (the PalmOS ROM version constant) and that macro would silently mangle a
 * member literally named "version" into a parse error. */
typedef struct { UInt16 defVer; Boolean showHidden; } CryptoDefaults;
